//               categories 和 items 都寫的話，符合任何一個的商品都適用
//   start       （可省略）開始日期，格式 "2026-11-01"
//   end         （可省略）結束日期，格式 "2026-11-30"（當天仍可使用）
//   enabled     （可省略）寫 false 就先停用這組促銷
//
// 注意：同一個商品符合多組促銷時，只會採用折最多的那一組，不會疊加。
// 注意：折扣不會讓商品價格低於 0 元。
// 注意：日期是用買家手機的日期判斷，收到訂單時請你自己再確認一次促銷是否有效。
